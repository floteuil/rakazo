export const SOVEREIGN_SKILLS_CATALOG: SovereignSkillCatalogEntry[] = SOVEREIGN_SKILL_PACKS.flatMap(
  (pack) => pack.skills,
);

const SKILLS_BY_SLUG = new Map<string, SovereignSkillCatalogEntry>(
  SOVEREIGN_SKILLS_CATALOG.map((skill) => [skill.slug, skill]),
);

const PACKS_BY_ID = new Map<string, SovereignSkillPack>(
  SOVEREIGN_SKILL_PACKS.map((pack) => [pack.id, pack]),
);

export function toSovereignSkillId(slug: string): string {
  return `sov-skill:${slug
    .replace(/^sov-skill:/, "")
    .trim()
    .toLowerCase()}`;
}

export function isSovereignSkillId(idOrSlug: string): boolean {
  if (idOrSlug.startsWith("sov-skill:")) {
    return SKILLS_BY_SLUG.has(idOrSlug.slice("sov-skill:".length).toLowerCase());
  }
  return SKILLS_BY_SLUG.has(idOrSlug.toLowerCase());
}

export function extractSovereignSkillSlug(idOrSlug: string): string {
  return idOrSlug
    .replace(/^sov-skill:/i, "")
    .trim()
    .toLowerCase();
}

export function getSovereignSkillBySlug(idOrSlug: string): SovereignSkillCatalogEntry | undefined {
  const slug = extractSovereignSkillSlug(idOrSlug);
  return SKILLS_BY_SLUG.get(slug);
}

export function getSovereignPackById(packId: string): SovereignSkillPack | undefined {
  return PACKS_BY_ID.get(packId);
}
